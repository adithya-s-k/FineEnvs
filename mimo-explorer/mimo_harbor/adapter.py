"""Turn one MiMo-V2.6-RL-oss row into one Harbor task directory.

Every value here comes from the explorer's runner (app/runner/domains.py), which mirrors Xiaomi's harness
(XiaomiMiMo/verl + mimoagent) and is the "original" side of the parity runs. Output is deterministic: the same
source revision, image lock and adapter version give byte-identical task directories.

Layout of a generated task:
    task.toml         [environment].docker_image pinned by digest; setup runs once from [environment.healthcheck]
    instruction.md    the prompt the explorer gives OpenCode, word for word
    environment/      Dockerfile (FROM the same digest) and setup/, the readable copy of what the healthcheck runs
    tests/            test.sh and everything grading needs; Harbor uploads it only after the agent finishes
"""

