"""Export eval runs as data.ts for the hf-motion comparison video.

    python eval/export_video.py runs <hf-motion>/src/AdithyaSK/scott-wu-math-race/data.ts

Race lanes use the 6,843 hand from the video (split video, index 1), sample 0 of each model, in the
"think" and "direct" modes. The board uses the 20 test deals in all three modes. Nothing is edited:
answers, values, latencies and reasoning text are the recorded ones.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODELS = json.loads((HERE / "models.json").read_text())["models"]
ORDER = [m["label"] for m in MODELS]


def load(run_dir: Path, name: str) -> list[dict]:
    return [json.loads(line) for line in (run_dir / name / "episodes.jsonl").read_text().splitlines() if line.strip()]


def ticker(r: dict) -> str:
    """The model's own words while it works: reasoning if the API returns it, else the visible reply."""
    text = (r.get("reasoning") or "").strip() or (r.get("text") or "").strip()
    text = re.sub(r"<answer>.*?</answer>", "", text, flags=re.S)
    text = re.sub(r"(?<=[\d)])\s*\*\s*(?=[\d(])", " × ", text)  # multiplication, before markdown asterisks go
    text = re.sub(r"[*#`_]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:700]


def lane(r: dict) -> dict:
    res = r.get("result") or {}
    check = res.get("check") or {}
    if r.get("api_error"):
        status = "error"
    elif res.get("exact"):
        status = "exact"
    elif r.get("answer") is None:
        status = "truncated" if r.get("stop") in ("length", "max_tokens", "incomplete") else "no-answer"
    elif not res.get("valid"):
        status = "invalid"
    else:
        status = "wrong"
    return {
        "label": r["label"],
        "org": r["org"],
        "open": r["open"],
        "floor": r["floor"],
        "latency": r["latency_s"],
        "tokens": r.get("output_tokens") or 0,
        "reward": r.get("reward") or 0.0,
        "answer": r.get("answer") or "",
        "value": check.get("value"),
        "status": status,
        "error": (res.get("error") or "")[:80],
        "ticker": ticker(r),
    }


def main(run_dir: str, out: str) -> None:
    runs = Path(run_dir)
    race = {}
    for mode in ("think", "direct"):
        rows = [r for r in load(runs, f"video-{mode}") if r["index"] == 1 and r["sample"] == 0]
        by = {r["label"]: r for r in rows}
        race[mode] = [lane(by[label]) for label in ORDER if label in by]
    hands = {}
    for mode in ("think", "nothink", "direct"):
        counts = defaultdict(lambda: [0, 0])
        for r in load(runs, f"video-{mode}"):
            c = counts[r["label"]]
            c[0] += bool((r.get("result") or {}).get("exact"))
            c[1] += 1
        hands[mode] = {k: v for k, v in counts.items()}
    board = []
    for m in MODELS:
        row = {"label": m["label"], "org": m["org"], "open": m["open"]}
        for mode in ("think", "nothink", "direct"):
            rs = [r for r in load(runs, f"test20-{mode}") if r["label"] == m["label"]]
            row[mode] = sum(bool((r.get("result") or {}).get("exact")) for r in rs)
            row[mode + "Floor"] = bool(rs and rs[0]["floor"])
        row["hands"] = {mode: hands[mode].get(m["label"], [0, 0]) for mode in hands}
        board.append(row)
    task = json.loads((HERE.parent / "envs/scott_wu_math/data/tasks/video.jsonl").read_text().splitlines()[1])
    data = {
        "hand": {"target": task["target"], "cards": task["cards"], "steps": task["solution_steps"]},
        "race": race,
        "board": board,
        "boardTasks": 20,
    }
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(
        "// Generated by FineEnvs 08-math-environments/scott-wu-math/eval/export_video.py from real eval runs. Do not edit by hand.\n"
        "/* eslint-disable */\n"
        "export type Lane = { label: string; org: string; open: boolean; floor: boolean; latency: number; tokens: number;\n"
        "  reward: number; answer: string; value: string | null; status: string; error: string; ticker: string };\n"
        "export type BoardRow = { label: string; org: string; open: boolean; think: number; nothink: number; direct: number;\n"
        "  thinkFloor: boolean; nothinkFloor: boolean; directFloor: boolean; hands: Record<string, number[]> };\n"
        "export type Data = { hand: { target: number; cards: { rank: number; suit: string; label: string }[]; steps: string[] };\n"
        "  race: { think: Lane[]; direct: Lane[] }; board: BoardRow[]; boardTasks: number };\n"
        f"export const DATA: Data = {json.dumps(data, ensure_ascii=False, indent=1)};\n"
    )
    print(f"wrote {out}")
    for mode, lanes in race.items():
        print(mode, [(l["label"], l["status"], l["latency"]) for l in lanes])


if __name__ == "__main__":
    main(*sys.argv[1:3])
