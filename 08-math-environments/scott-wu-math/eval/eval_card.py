"""Write results/eval-v1.json, the catalog's eval card, from the test20 runs of eval/rollout.py.

One model row per model and mode (think, nothink, direct), with the mean reward, a 95% bootstrap
interval over the 20 deals, and how many answers were solved and valid.

    python eval/eval_card.py --runs runs --out results/eval-v1.json
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODES = {
    "think": "the model's own reasoning at high effort, up to 32k output tokens",
    "nothink": "reasoning off, or as low as the API allows, up to 32k output tokens",
    "direct": "no reasoning, the answer tag alone, 300 output tokens",
}


def ci95(values: list[float], n_boot: int = 10_000, seed: int = 0) -> list[float]:
    rng = random.Random(seed)
    means = sorted(sum(rng.choices(values, k=len(values))) / len(values) for _ in range(n_boot))
    return [round(means[int(0.025 * n_boot)], 3), round(means[int(0.975 * n_boot) - 1], 3)]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=HERE.parent / "runs")
    ap.add_argument("--out", type=Path, default=HERE.parent / "results" / "eval-v1.json")
    args = ap.parse_args()

    labels = {m["id"]: m for m in json.loads((HERE / "models.json").read_text())["models"]}
    rows, indices, date = [], None, None
    for mode in MODES:
        run_dir = args.runs / f"test20-{mode}"
        run = json.loads((run_dir / "run.json").read_text())
        indices = run["indices"]
        date = date or run["started"]
        by_model: dict[str, list[dict]] = {}
        for line in (run_dir / "episodes.jsonl").read_text().splitlines():
            ep = json.loads(line)
            by_model.setdefault(ep["model"], []).append(ep)
        for model, eps in by_model.items():
            rewards = [ep["reward"] for ep in eps]
            rows.append({
                "model": labels[model]["label"],
                "provider": labels[model]["org"],
                "mode": mode,
                "lowest_effort": bool(eps[0].get("floor")),
                "runs": len(eps),
                "mean": round(sum(rewards) / len(rewards), 4),
                "ci95": ci95(rewards),
                "solved": sum(1 for ep in eps if (ep.get("result") or {}).get("exact")),
                "valid": sum(1 for ep in eps if (ep.get("result") or {}).get("valid")),
                "mean_output_tokens": round(sum(ep.get("output_tokens") or 0 for ep in eps) / len(eps)),
            })
    order = list(MODES)
    rows.sort(key=lambda r: (order.index(r["mode"]), -r["mean"], r["model"]))

    card = {
        "env": "scott-wu-math",
        "version": "v1",
        "authors": [{"name": "Adithya S Kolavi", "github": "adithya-s-k", "affiliation": "Hugging Face"}],
        "framework": "openenv",
        "tasks": {
            "split": "test",
            "n": len(indices),
            "source": "deals generated by envs/scott_wu_math/scripts/build_tasks.py; every deal is checked by the solver to have a solution",
            "selection": "the first five test deals of each level (24, three-digit, year, four-digit): indices "
                         + ", ".join(map(str, indices)),
        },
        "harness": {
            "agent": "eval/rollout.py, one OpenEnv session per episode",
            "tools": [],
            "max_turns": 1,
            "modes": MODES,
        },
        "grading": {
            "reference": "the target, made from every card exactly once with + - x / and parentheses",
            "reward": "1.0 for an exact answer; 0.3 c^2 with c = 1 - |value - target| / (0.1 target) for a valid "
                      "expression within 10% of the target; 0 otherwise",
            "excused": "nothing",
            "judge": False,
        },
        "baselines": [],
        "models": rows,
        "links": {
            "play": "https://huggingface.co/spaces/FineEnvs/ScottWuMath",
            "code": "https://github.com/adithya-s-k/FineEnvs/tree/main/08-math-environments/scott-wu-math",
        },
        "date": __import__("datetime").date.fromtimestamp(date).isoformat(),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(card, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {args.out}: {len(rows)} rows")


if __name__ == "__main__":
    main()
