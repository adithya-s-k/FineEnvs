"""Export the two video hands as rounds for the "Scott Wu vs. the models" video (hf-motion ScottWuMathEnv).

    python eval/export_vs.py runs <hf-motion>/src/AdithyaSK/scott-wu-math-env/data.ts

Round 1: the 2025 hand (video index 0), reasoning on. Round 2: the 6,843 hand (index 1), reasoning on (no token cap beyond the 32k default).
Sample 0 of every model, as recorded.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from export_video import ORDER, lane, load  # noqa: E402

ROUNDS = [("think", 0), ("think", 1)]


def main(run_dir: str, out: str) -> None:
    runs = Path(run_dir)
    hands = [json.loads(l) for l in (HERE.parent / "envs/scott_wu_math/data/tasks/video.jsonl").read_text().splitlines()]
    rounds = []
    for mode, index in ROUNDS:
        rows = {r["label"]: r for r in load(runs, f"video-{mode}") if r["index"] == index and r["sample"] == 0}
        hand = hands[index]
        rounds.append(
            {
                "mode": mode,
                "target": hand["target"],
                "cards": hand["cards"],
                "solution": hand["solution"],
                "lanes": [lane(rows[label]) for label in ORDER if label in rows],
            }
        )
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(
        "// Generated by FineEnvs 08-math-environments/scott-wu-math/eval/export_vs.py from real eval runs. Do not edit by hand.\n"
        "/* eslint-disable */\n"
        "export type Lane = { label: string; org: string; open: boolean; floor: boolean; latency: number; tokens: number;\n"
        "  reward: number; answer: string; value: string | null; status: string; error: string; ticker: string };\n"
        "export type Round = { mode: string; target: number; cards: { rank: number; suit: string; label: string }[];\n"
        "  solution: string; lanes: Lane[] };\n"
        f"export const ROUNDS: Round[] = {json.dumps(rounds, ensure_ascii=False, indent=1)};\n"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
